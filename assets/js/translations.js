function applyTranslation(lang) {
  const t = translations[lang];
  document.documentElement.lang = lang;
  if (!t) return;

  // Helper to safely set text
  const setText = (selector, value) => {
    const el = document.querySelector(selector);
    if (el) el.textContent = value;
  };

  // Sidebar
  setText(".sidebar .name", t.name);
  setText(".sidebar .title", t.title);
  setText(".info_more-btn span", t.show_contacts);

  const contactTitles = document.querySelectorAll(".contact-title");
  const labels = [t.email_label, t.phone_label, t.birthday_label, t.location_label];
  contactTitles.forEach((el, i) => { if (labels[i]) el.textContent = labels[i]; });

  const birthdayEl = document.querySelector(".contact-item time");
  if (birthdayEl) birthdayEl.textContent = t.birthday;

  const locationEl = document.querySelector(".contact-item address");
  if (locationEl) locationEl.textContent = t.location;

  // Navbar links
  const navLinks = document.querySelectorAll("[data-nav-link]");
  const navKeys = [t.nav_about, t.nav_resume, t.nav_portfolio];
  navLinks.forEach((el, i) => { if (navKeys[i]) el.textContent = navKeys[i]; });

  // About page
  setText("[data-page='about'] .article-title", t.about_title);
  const aboutPs = document.querySelectorAll(".about-text p");
  if (aboutPs[0]) aboutPs[0].textContent = t.about_p1;
  if (aboutPs[1]) aboutPs[1].textContent = t.about_p2;

  // Languages section
  setText(".languages-title", t.languages_title);
  const langItems = document.querySelectorAll(".languages-item");
  const langValues = [t.lang_1, t.lang_2, t.lang_3, t.lang_4];
  langItems.forEach((el, i) => { if (langValues[i]) el.textContent = langValues[i]; });

  // Services
  setText(".service-title", t.services_title);
  const serviceTitles = document.querySelectorAll(".service-item-title");
  const serviceTexts = document.querySelectorAll(".service-item-text");
  const sTitles = [t.service_1_title];
  const sTexts = [t.service_1_text];
  serviceTitles.forEach((el, i) => { if (sTitles[i]) el.textContent = sTitles[i]; });
  serviceTexts.forEach((el, i) => { if (sTexts[i]) el.textContent = sTexts[i]; });

  // Resume page
  setText("[data-page='resume'] .article-title", t.resume_title);
  const timelineTitles = document.querySelectorAll(".timeline .h3");
  if (timelineTitles[0]) timelineTitles[0].textContent = t.education_title;
  if (timelineTitles[1]) timelineTitles[1].textContent = t.experience_title;
  setText(".skills-title", t.skills_title);
  setText(".tech-stack-title", t.tech_stack_title);

  const timelineItems = document.querySelectorAll(".timeline-item");
  const timelineData = [
    { title: t.edu_1_title, date: t.edu_1_date, text: t.edu_1_text },
    { title: t.exp_1_title, date: t.exp_1_date, text: t.exp_1_text },
    { title: t.exp_2_title, date: t.exp_2_date, text: t.exp_2_text },
  ];
  timelineItems.forEach((item, i) => {
    if (!timelineData[i]) return;
    const titleEl = item.querySelector(".timeline-item-title");
    const spanEl = item.querySelector("span");
    const textEl = item.querySelector(".timeline-text");
    if (titleEl) titleEl.textContent = timelineData[i].title;
    if (spanEl) spanEl.textContent = timelineData[i].date;
    if (textEl) textEl.innerHTML = timelineData[i].text.replace(/\n/g, "<br>");
  });

  // Portfolio page
  setText("[data-page='portfolio'] .article-title", t.portfolio_title);
  setText(".portfolio-section-title", t.portfolio_section_title);
  const appCards = document.querySelectorAll(".application-card");
  const appTexts = [t.belet_text, t.sowgatlar_text, t.yunus_text, t.car_services_text];
  appCards.forEach((card, i) => {
    const categoryEl = card.querySelector(".application-category");
    const textEl = card.querySelector(".application-text");
    const linkEl = card.querySelector(".application-link");
    if (categoryEl) categoryEl.textContent = t.app_category;
    if (textEl && appTexts[i]) textEl.textContent = appTexts[i];
    if (linkEl) {
      linkEl.textContent = linkEl.href.includes("github.com") ? t.github_button : t.play_store_button;
    }
  });
  const filterBtns = document.querySelectorAll("[data-filter-btn]");
  const selectBtns = document.querySelectorAll("[data-select-item] button");
  const filterLabels = [t.filter_all, t.filter_webdesign, t.filter_apps, t.filter_webdev];
  filterBtns.forEach((el, i) => { if (filterLabels[i]) el.textContent = filterLabels[i]; });
  selectBtns.forEach((el, i) => { if (filterLabels[i]) el.textContent = filterLabels[i]; });
}

// Language switcher buttons
const langBtns = document.querySelectorAll("[data-lang]");
langBtns.forEach(btn => {
  btn.addEventListener("click", function () {
    langBtns.forEach(b => b.classList.remove("active"));
    this.classList.add("active");
    applyTranslation(this.dataset.lang);
  });
});

const translatedNavigationLinks = document.querySelectorAll("[data-nav-link]");
const translatedPages = document.querySelectorAll("[data-page]");

for (let i = 0; i < translatedNavigationLinks.length; i++) {
  translatedNavigationLinks[i].addEventListener("click", function () {

    const clickedIndex = Array.from(translatedNavigationLinks).indexOf(this);

    for (let i = 0; i < translatedPages.length; i++) {
      if (i === clickedIndex) {
        translatedPages[i].classList.add("active");
        translatedNavigationLinks[i].classList.add("active");
        window.scrollTo(0, 0);
      } else {
        translatedPages[i].classList.remove("active");
        translatedNavigationLinks[i].classList.remove("active");
      }
    }

  });
}

